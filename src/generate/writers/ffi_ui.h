#pragma once

#include <cstddef>
#include <functional>
#include <map>
#include <string>
#include <string_view>
#include <vector>

// One call-site parameter of a descriptor callable, in target-language spelling.
struct FfiUiParam
{
    std::string name;
    std::string type;
};

// A single callable from a schema-1 descriptor. `sentinels` is meaningful for constructors
// only; it maps a parameter name to the literal the backend emits when the caller omits it.
struct FfiUiCall
{
    std::string symbol;
    std::vector<FfiUiParam> params;
    std::string idiom;
    std::string owner;
    std::string returns;
    std::string reason;
    std::map<std::string, std::string, std::less<>> sentinels;

    // A callable is usable when it names a symbol and does not use the `unsupported` idiom.
    [[nodiscard]] bool IsUsable() const noexcept
    {
        return !symbol.empty() && idiom != "unsupported";
    }
};

// One entry of `classes` in a schema-1 descriptor.
struct FfiUiClass
{
    std::string type;
    std::string idiom;
    FfiUiCall ctor;
    std::map<std::string, FfiUiCall, std::less<>> roles;
    std::map<std::string, std::string, std::less<>> constants;
};

// Transparent-comparator maps so lookups can take a std::string_view without allocating.
using FfiUiCallMap = std::map<std::string, FfiUiCall, std::less<>>;
using FfiUiClassMap = std::map<std::string, FfiUiClass, std::less<>>;
using FfiUiStringMap = std::map<std::string, std::string, std::less<>>;

// One `unsupported[]` entry: a (class, role) pair the language cannot satisfy.
struct FfiUiUnsupported
{
    std::string wx_class;
    std::string role;
    std::string reason;
};

// Schema-1 descriptor for one language, loaded from src/generate/ffi_ui/<lang>.json.
//
// The six descriptors are generated by `kwxgen emit-ui`; never hand-edit them. The global
// blocks are keyed the same way the descriptor names them:
//   sizers: "wxBoxSizer.ctor", "wxBoxSizer.add_window", "flags.expand", ...
//   events: "bind", "bind_id"
//   bitmap: "from_base64", "get_bitmap", "delete"
//   font:   "create", "delete"
//   std_buttons: "create", "add_button", "realize"
struct FfiUiDescriptor
{
    int schema {};
    std::string lang;
    std::string tool;
    std::string version;
    std::string headers_hash;
    std::string profile;
    std::map<std::string, std::string, std::less<>> naming;
    FfiUiClassMap classes;
    FfiUiCallMap sizers;
    FfiUiCallMap events;
    FfiUiCallMap bitmap;
    FfiUiCallMap font;
    FfiUiCallMap std_buttons;
    FfiUiCall set_top_window;
    std::string app_entry;
    std::string app_entry_signature;
    bool app_emit_entry {};
    std::vector<FfiUiUnsupported> unsupported;
};

// Returns true for the six languages that have a kwxgen UI descriptor.
[[nodiscard]] bool IsFfiUiLanguage(GenLang language);

// Absolute path to the directory holding the six descriptors, manifest.json and coverage.json.
// The returned path always ends with a directory separator. Discovery follows the same order as
// GetFfiUiDescriptor(); callers that read a file must still check that it exists.
[[nodiscard]] std::string GetFfiUiDirPath();

// Returns the cached descriptor for `language`, or nullptr when the descriptor is absent,
// invalid, or stale relative to manifest.json. A failure is reported exactly once per language
// through stderr and the command-line log; it never throws and never writes a file.
[[nodiscard]] const FfiUiDescriptor* GetFfiUiDescriptor(GenLang language);

// Resolves `role` for `wx_class` in the same order `kwxgen check-ui` does. Returns true only
// when the resolved callable is usable. `out` receives the callable that was found (which may
// be unusable, with `reason` set) so the caller can report why resolution failed.
[[nodiscard]] bool ResolveRole(const FfiUiDescriptor& descriptor, std::string_view wx_class,
                               std::string_view role, FfiUiCall& out);

// Reports one diagnostic naming the language, class, role and, when the descriptor records it,
// the reason code. Each report is counted so the command-line summary can state the total.
void ReportUnsupportedRole(const FfiUiDescriptor& descriptor, std::string_view wx_class,
                           std::string_view role);

// Number of unsupported-role diagnostics reported since the last reset.
[[nodiscard]] std::size_t GetFfiUiDiagnosticCount();
void ResetFfiUiDiagnosticCount();
