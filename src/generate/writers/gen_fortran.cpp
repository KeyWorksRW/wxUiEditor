FortranCodeGenerator::FortranCodeGenerator(Node* form_node) :
    BaseCodeGenerator(GenLang::fortran, form_node)
{
}

void FortranCodeGenerator::GenerateClass(GenLang language, PANEL_PAGE panel_type,
                                         wxProgressDialog* /* progress */)
{
    m_language = language;
    m_panel_type = panel_type;
    ASSERT(m_language == GenLang::fortran);
    m_embedded_images.clear();
    SetImagesForm();
    std::set<std::string> img_include_set;
    CollectImageHeaders(m_form_node, img_include_set);
    ParseImageProperties(m_form_node);

    if (m_header)
    {
        m_header->Clear();
    }
    m_source->Clear();
    SetLanguageIndent(m_source, m_language);
    m_source->SetLastLineBlank();

    // File header comment
    m_source->writeLine("! This file was generated by wxUiEditor. Do not edit.");
    m_source->writeLine();

    if (m_form_node->is_Gen(gen_Images))
    {
        return;
    }

    if (!IsFfiUiLanguage(m_language))
    {
        return;
    }

    const FfiFormInfo info = GetFfiFormInfo(m_form_node, m_language);
    const std::string subroutine = "create_" + info.snake;
    const std::string module = info.basename + "_mod";

    m_source->writeLine("module " + module);
    m_source->Indent();
    m_source->writeLine("use, intrinsic :: iso_c_binding");
    for (const std::string& use_module: GetFortranUseModules(m_language, m_form_node))
    {
        m_source->writeLine("use " + use_module);
    }
    m_source->writeLine("implicit none");
    m_source->Unindent();
    m_source->writeLine("contains");
    m_source->writeLine();
    m_source->Indent();
    m_source->writeLine("subroutine " + subroutine + "(parent, form)");
    m_source->Indent();
    m_source->writeLine("type(c_ptr), intent(in) :: parent");
    m_source->writeLine("type(c_ptr), intent(out) :: form");

    // C3 fixes the entry's signature to two c_ptr arguments, but every kwxFortran wrapper takes
    // and returns derived-type handles. Bridge the two shapes with one local of each kind: the
    // body constructs `form_window` from `parent_window`, and `form` receives form_window%ptr.
    const std::string form_class(m_form_node->get_DeclName());
    m_source->writeLine("type(wxwindow_t) :: parent_window");
    m_source->writeLine("type(" + GetFortranLocalType(m_language, form_class) + ") :: form_window");

    std::string declarations;
    std::string handlers;
    declarations.clear();
    handlers.clear();

    // The emitter fills `declarations` on its first pass, but the declarations must be written
    // before any statement. Run the body into a scratch writer first, then replay it.
    // WriteCode calls doWrite() once per fragment (indentation, text, newline), so the scratch
    // collects one buffer and splits it on newlines when it is replayed.
    class ScratchWriter : public WriteCode
    {
    public:
        void Clear() override { m_text.clear(); }
        [[nodiscard]] const std::string& GetText() const { return m_text; }

    protected:
        void doWrite(std::string_view text) override { m_text.append(text); }

    private:
        std::string m_text;
    };

    ScratchWriter scratch;
    scratch.SetTabToSpaces(GetLanguageIndentSize(m_language),
                           GetLanguageIndentWithTabs(m_language));

    Code scratch_code(m_form_node, m_language);
    std::ignore = EmitFfiFormBody(scratch_code, &scratch, m_form_node, info, "form_window",
                                  declarations, handlers, "parent_window");

    // Every declaration must precede the first executable statement: the generated locals
    // first, then the embedded-image constant (which declares and then assigns).
    if (!declarations.empty())
    {
        m_source->writeLine(declarations);
    }
    if (!m_embedded_images.empty())
    {
        WriteImageConstruction(scratch_code);
    }
    m_source->writeLine();
    m_source->writeLine("parent_window%ptr = parent");

    const std::string body_text = scratch.GetText();
    size_t body_start = 0;
    while (body_start <= body_text.size())
    {
        const size_t body_end = body_text.find('\n', body_start);
        const std::string line = body_text.substr(
            body_start, body_end == std::string::npos ? std::string::npos : body_end - body_start);
        if (!line.empty())
        {
            m_source->writeLine(line);
        }
        if (body_end == std::string::npos)
        {
            break;
        }
        body_start = body_end + 1;
    }

    m_source->writeLine("form = form_window%ptr");

    m_source->Unindent();
    m_source->writeLine("end subroutine " + subroutine);
    m_source->Unindent();

    if (!handlers.empty())
    {
        m_source->writeLine();
        m_source->writeLine(handlers);
    }

    m_source->ResetIndent();
    m_source->writeLine();
    m_source->writeLine("end module " + module);

    if (wxString sourcemap; wxGetEnv("WXUE_FFI_SOURCEMAP", &sourcemap) && !sourcemap.empty())
    {
        auto [output_path, has_base_file] = Project.GetOutputPath(m_form_node, m_language);
        if (has_base_file)
        {
            WriteFfiSourceMap(output_path.c_str());
        }
    }
}
